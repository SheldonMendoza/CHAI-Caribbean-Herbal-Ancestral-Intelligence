#!/usr/bin/env node
/**
 * CHAI — generate-seed-sql.mjs
 *
 * Reads data/seed-plants.json (schema documented in contracts/seed-format.md)
 * and writes migrations/0002_seed.sql.
 *
 * Idempotent: the generated SQL first DELETEs every row belonging to the seed
 * plants/sources in FK-safe order, then re-INSERTs everything. Re-running the
 * migration yields the same final state.
 *
 * Schema notes:
 *   - plants.safety_* columns store the seed safety object verbatim.
 *   - traditional_uses and evidence_assessments get explicit seed-scoped ids
 *     (1..N) so their source link tables can be populated deterministically.
 *
 * NEVER hand-edit migrations/0002_seed.sql — regenerate it with this script.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IN_PATH = join(ROOT, 'data', 'seed-plants.json');
const OUT_PATH = join(ROOT, 'migrations', '0002_seed.sql');

const EVIDENCE_CATEGORIES = new Set([
  'strong_human',
  'moderate_human',
  'preliminary',
  'traditional_use_documented',
  'insufficient_evidence',
  'safety_concern',
]);

const warnings = [];
function warn(msg) {
  warnings.push(msg);
  console.warn('WARNING:', msg);
}

/** SQL string literal. Empty string / null / undefined -> NULL (optional fields). */
function sqlStr(v) {
  if (v === null || v === undefined || v === '') return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** SQL string literal for NOT NULL fields; throws when blank. */
function sqlStrRequired(v, label) {
  if (v === null || v === undefined || String(v) === '') {
    throw new Error(`Missing required field: ${label}`);
  }
  return sqlStr(v);
}

function sqlInt(v) {
  if (v === null || v === undefined || v === '') return 'NULL';
  if (!Number.isInteger(v)) throw new Error(`Expected integer, got: ${JSON.stringify(v)}`);
  return String(v);
}

function sqlJson(v) {
  if (v === null || v === undefined) return 'NULL';
  return sqlStr(JSON.stringify(v));
}

function sqlBool(v) {
  return v ? '1' : '0';
}

function main() {
  let raw;
  try {
    raw = readFileSync(IN_PATH, 'utf8');
  } catch {
    console.error(`ERROR: seed file not found: ${IN_PATH}`);
    console.error('The research workstream has not delivered data/seed-plants.json yet.');
    process.exit(1);
  }

  const seed = JSON.parse(raw);
  if (typeof seed.version !== 'number') throw new Error('seed.version must be a number');
  if (!Array.isArray(seed.sources)) throw new Error('seed.sources must be an array');
  if (!Array.isArray(seed.plants)) throw new Error('seed.plants must be an array');
  if (seed.plants.length === 0) throw new Error('seed.plants is empty — nothing to seed');

  const sourceById = new Map();
  for (const s of seed.sources) {
    if (!s.id) throw new Error('A source is missing its id');
    if (sourceById.has(s.id)) throw new Error(`Duplicate source id: ${s.id}`);
    sourceById.set(s.id, s);
  }

  const plantIds = seed.plants.map((p) => {
    if (!p.id) throw new Error('A plant is missing its id');
    if (!p.slug) throw new Error(`Plant ${p.id} is missing its slug`);
    return p.id;
  });
  const sourceIds = [...sourceById.keys()];

  const plantIdList = plantIds.map((id) => `'${id.replace(/'/g, "''")}'`).join(', ');
  const sourceIdList = sourceIds.map((id) => `'${id.replace(/'/g, "''")}'`).join(', ');

  const L = [];
  L.push('-- CHAI seed data — migrations/0002_seed.sql');
  L.push('-- GENERATED by scripts/generate-seed-sql.mjs from data/seed-plants.json');
  L.push('-- DO NOT hand-edit. Regenerate with: node scripts/generate-seed-sql.mjs');
  L.push(`-- seed version: ${seed.version}, exported: ${seed.exported ?? 'unknown'}`);
  L.push(`-- plants: ${seed.plants.length}, sources: ${seed.sources.length}`);
  L.push('-- Seed claims/uses/assessments use explicit ids 1..N (safe: all seed rows are deleted below first).');
  L.push('');

  // ---- Idempotent DELETEs, FK-safe (children before parents) ----
  L.push('-- Idempotent teardown: remove any previous seed rows, children first.');
  L.push(`DELETE FROM evidence_assessment_sources WHERE assessment_id IN (SELECT ea.id FROM evidence_assessments ea WHERE ea.claim_id IN (SELECT id FROM claims WHERE plant_id IN (${plantIdList})));`);
  L.push(`DELETE FROM evidence_assessments WHERE claim_id IN (SELECT id FROM claims WHERE plant_id IN (${plantIdList}));`);
  L.push(`DELETE FROM claims WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM traditional_use_sources WHERE traditional_use_id IN (SELECT id FROM traditional_uses WHERE plant_id IN (${plantIdList}));`);
  L.push(`DELETE FROM plant_images WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM plant_sources WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM traditional_uses WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM distribution WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM plant_names WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM saved_plants WHERE plant_id IN (${plantIdList});`);
  L.push(`DELETE FROM plants WHERE id IN (${plantIdList});`);
  if (sourceIds.length > 0) {
    L.push(`DELETE FROM plant_sources WHERE source_id IN (${sourceIdList});`);
    L.push(`DELETE FROM sources WHERE id IN (${sourceIdList});`);
  }
  L.push('');

  const now = new Date().toISOString();

  // ---- sources ----
  L.push('-- sources');
  for (const s of seed.sources) {
    L.push(
      `INSERT INTO sources (id, title, authors, year, journal, doi, url, source_type, accessed_date, notes) VALUES (` +
        `${sqlStrRequired(s.id, 'source.id')}, ${sqlStrRequired(s.title, `source ${s.id} title`)}, ` +
        `${sqlStr(s.authors)}, ${sqlInt(s.year)}, ${sqlStr(s.journal)}, ${sqlStr(s.doi)}, ` +
        `${sqlStr(s.url)}, ${sqlStrRequired(s.source_type, `source ${s.id} source_type`)}, ` +
        `${sqlStr(s.accessed)}, ${sqlStr(s.notes)});`,
    );
  }
  L.push('');

  // ---- plants + children ----
  let claimId = 0;
  let useId = 0;
  let assessId = 0;
  for (const p of seed.plants) {
    const pid = sqlStrRequired(p.id, 'plant.id');
    const safety = p.safety ?? {};

    L.push(`-- plant: ${p.id}`);
    L.push(
      `INSERT INTO plants (id, slug, common_name, scientific_name, scientific_name_authorship, family, ` +
        `botanical_description, identification, parts_used, constituents, cultural_background, ` +
        `traditional_use_summary, disambiguation_note, safety_summary, side_effects, interactions, ` +
        `pregnancy, children, contraindications, reviewer_status, featured, last_reviewed, created_at) VALUES (` +
        `${pid}, ${sqlStrRequired(p.slug, `plant ${p.id} slug`)}, ` +
        `${sqlStrRequired(p.common_name, `plant ${p.id} common_name`)}, ` +
        `${sqlStrRequired(p.scientific_name, `plant ${p.id} scientific_name`)}, ` +
        `${sqlStr(p.scientific_name_authorship)}, ${sqlStrRequired(p.family, `plant ${p.id} family`)}, ` +
        `${sqlStr(p.botanical_description)}, ${sqlStr(p.identification)}, ` +
        `${sqlJson(p.parts_used)}, ${sqlJson(p.constituents)}, ${sqlStr(p.cultural_background)}, ` +
        `${sqlStr(p.traditional_use_summary)}, ${sqlStr(p.disambiguation_note)}, ` +
        `${sqlStr(safety.summary)}, ${sqlStr(safety.side_effects)}, ${sqlStr(safety.interactions)}, ` +
        `${sqlStr(safety.pregnancy)}, ${sqlStr(safety.children)}, ${sqlStr(safety.contraindications)}, ` +
        `${sqlStr(p.reviewer_status ?? 'draft')}, ${sqlBool(p.featured)}, ` +
        `${sqlStr(p.last_reviewed)}, ${sqlStr(now)});`,
    );

    for (const n of p.names ?? []) {
      L.push(
        `INSERT INTO plant_names (plant_id, name, name_type, region, notes) VALUES (` +
          `${pid}, ${sqlStrRequired(n.name, `plant ${p.id} name`)}, ` +
          `${sqlStrRequired(n.name_type, `plant ${p.id} name_type`)}, ${sqlStr(n.region)}, ${sqlStr(n.notes)});`,
      );
    }

    for (const d of p.distribution ?? []) {
      L.push(
        `INSERT INTO distribution (plant_id, country, status, note) VALUES (` +
          `${pid}, ${sqlStrRequired(d.country, `plant ${p.id} distribution country`)}, ` +
          `${sqlStr(d.status)}, ${sqlStr(d.note)});`,
      );
    }

    for (const u of p.traditional_uses ?? []) {
      useId += 1;
      const uid = useId;
      L.push(
        `INSERT INTO traditional_uses (id, plant_id, use_text, countries, preparation) VALUES (` +
          `${uid}, ${pid}, ${sqlStrRequired(u.use, `plant ${p.id} traditional use text`)}, ` +
          `${sqlJson(u.countries)}, ${sqlStr(u.preparation)});`,
      );
      for (const sid of u.source_ids ?? []) {
        if (!sourceById.has(sid)) throw new Error(`plant ${p.id}: traditional-use source_ids references unknown source ${sid}`);
        L.push(`INSERT INTO traditional_use_sources (traditional_use_id, source_id) VALUES (${uid}, ${sqlStr(sid)});`);
      }
    }

    // plant_sources: derive from plants' implicit source links — the seed format
    // has no top-level plant<->source links, so link every source referenced by
    // this plant's claims/uses so the union query in getPlantDetail finds them.
    const linkedSources = new Set();
    for (const c of p.claims ?? []) {
      for (const a of c.assessments ?? []) {
        for (const sid of a.source_ids ?? []) {
          if (!sourceById.has(sid)) throw new Error(`plant ${p.id}: assessment source_ids references unknown source ${sid}`);
          linkedSources.add(sid);
        }
      }
    }
    for (const sid of linkedSources) {
      L.push(`INSERT INTO plant_sources (plant_id, source_id) VALUES (${pid}, ${sqlStr(sid)});`);
    }

    for (const c of p.claims ?? []) {
      claimId += 1;
      const cid = claimId;
      L.push(
        `INSERT INTO claims (id, plant_id, claim_text) VALUES (${cid}, ${pid}, ` +
          `${sqlStrRequired(c.claim, `plant ${p.id} claim text`)});`,
      );
      for (const a of c.assessments ?? []) {
        if (!EVIDENCE_CATEGORIES.has(a.category)) {
          throw new Error(`plant ${p.id}: invalid evidence category ${JSON.stringify(a.category)}`);
        }
        const sids = Array.isArray(a.source_ids) ? a.source_ids : [];
        for (const sid of sids) {
          if (!sourceById.has(sid)) throw new Error(`plant ${p.id}: assessment source_ids references unknown source ${sid}`);
        }
        assessId += 1;
        const aid = assessId;
        L.push(
          `INSERT INTO evidence_assessments (id, claim_id, category, summary, study_design, population, ` +
            `preparation_studied, main_findings, limitations, adverse_effects, reviewer_status, last_reviewed) VALUES (` +
            `${aid}, ${cid}, ${sqlStr(a.category)}, ${sqlStrRequired(a.summary, `plant ${p.id} assessment summary`)}, ` +
            `${sqlStr(a.study_design)}, ${sqlStr(a.population)}, ${sqlStr(a.preparation_studied)}, ` +
            `${sqlStr(a.main_findings)}, ${sqlStr(a.limitations)}, ${sqlStr(a.adverse_effects)}, ` +
            `${sqlStr(a.reviewer_status ?? 'draft')}, ${sqlStr(a.last_reviewed)});`,
        );
        for (const sid of sids) {
          L.push(`INSERT INTO evidence_assessment_sources (assessment_id, source_id) VALUES (${aid}, ${sqlStr(sid)});`);
        }
      }
    }

    (p.images ?? []).forEach((img, i) => {
      L.push(
        `INSERT INTO plant_images (plant_id, url, caption, attribution, license, license_url, source_url, position) VALUES (` +
          `${pid}, ${sqlStrRequired(img.url, `plant ${p.id} image url`)}, ${sqlStr(img.caption)}, ` +
          `${sqlStrRequired(img.attribution, `plant ${p.id} image attribution`)}, ` +
          `${sqlStrRequired(img.license, `plant ${p.id} image license`)}, ` +
          `${sqlStrRequired(img.license_url, `plant ${p.id} image license_url`)}, ` +
          `${sqlStrRequired(img.source_url, `plant ${p.id} image source_url`)}, ${i});`,
      );
    });

    // audit trail: one row per plant, recording what was seeded
    const auditDetails = JSON.stringify({
      seed_version: seed.version,
      slug: p.slug,
      common_name: p.common_name,
    });
    L.push(
      `INSERT INTO audit_log (actor, action, target, details, created_at) VALUES (` +
        `'seed', 'seed.insert', ${pid}, ${sqlStr(auditDetails)}, ${sqlStr(now)});`,
    );
    L.push('');
  }

  L.push(
    `INSERT INTO audit_log (actor, action, target, details, created_at) VALUES (` +
      `'seed', 'seed.complete', NULL, ` +
      `${sqlStr(JSON.stringify({ seed_version: seed.version, plants: seed.plants.length, sources: seed.sources.length, warnings: warnings.length }))}, ` +
      `${sqlStr(now)});`,
  );

  writeFileSync(OUT_PATH, L.join('\n') + '\n', 'utf8');
  console.log(`Wrote ${OUT_PATH} (${seed.plants.length} plants, ${seed.sources.length} sources, ${claimId} claims)`);
  if (warnings.length > 0) {
    console.log(`${warnings.length} warning(s) — see above.`);
  }
}

main();
